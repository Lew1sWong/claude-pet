const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("petAPI", {
  onUsage: (cb) => ipcRenderer.on("usage", (_e, d) => cb(d)),
  onError: (cb) => ipcRenderer.on("usage-error", (_e, d) => cb(d)),
  onCelebrate: (cb) => ipcRenderer.on("celebrate", () => cb()),
  onCharacter: (cb) => ipcRenderer.on("character", (_e, c) => cb(c)),
  onPetSize: (cb) => ipcRenderer.on("pet-size", (_e, n) => cb(n)),
  onGeometry: (cb) => ipcRenderer.on("island-geometry", (_e, g) => cb(g)),
  onOpenGame: (cb) => ipcRenderer.on("open-game", (_e, k) => cb(k)),
  onBossShow: (cb) => ipcRenderer.on("boss-show", (_e, d) => cb(d)),
  onI18n: (cb) => ipcRenderer.on("i18n", (_e, d) => cb(d)),
  onFeatures: (cb) => ipcRenderer.on("features", (_e, d) => cb(d)),
  onCustomPets: (cb) => ipcRenderer.on("custom-pets", (_e, d) => cb(d)),
  onSettingsInit: (cb) => ipcRenderer.on("settings-init", (_e, d) => cb(d)),
  moveBy: (dx) => ipcRenderer.invoke("move-by", dx),
  enterGameMode: (w, h) => ipcRenderer.send("enter-game-mode", w, h),
  exitGameMode: () => ipcRenderer.send("exit-game-mode"),
  bossDismiss: () => ipcRenderer.send("boss-dismiss"),
  bossToggle: () => ipcRenderer.send("boss-toggle"),
  gameClear: () => ipcRenderer.send("stat-bump", "game"),
  onStats: (cb) => ipcRenderer.on("stats", (_e, s) => cb(s)),
  // 🌱 pixel garden
  onGarden: (cb) => ipcRenderer.on("garden", (_e, g) => cb(g)),
  gardenPlant: (i, crop) => ipcRenderer.send("garden-plant", i, crop),
  gardenHarvest: (i) => ipcRenderer.send("garden-harvest", i),
  gardenShoo: (i) => ipcRenderer.send("garden-shoo", i),
  shareReport: (dataUrl) => ipcRenderer.send("share-report", dataUrl),
  onSfx: (cb) => ipcRenderer.on("sfx", (_e, n) => cb(n)),
  dragStart: (offX, offY) => ipcRenderer.send("drag-start", offX, offY),
  dragEnd: () => ipcRenderer.send("drag-end"),
  setIgnore: (v) => ipcRenderer.send("set-ignore", v),
  setCharacter: (c) => ipcRenderer.send("set-character", c),
  setUiMode: (m) => ipcRenderer.send("set-ui-mode", m),
  showMenu: () => ipcRenderer.send("show-menu"),
  refresh: () => ipcRenderer.send("refresh"),
  quit: () => ipcRenderer.send("quit"),
  // settings window
  getSettings: () => ipcRenderer.invoke("get-settings"),
  settingsUpdate: (patch) => ipcRenderer.send("settings-update", patch),
  openSettings: () => ipcRenderer.send("open-settings"),
  closeSettings: () => ipcRenderer.send("close-settings"),
});
